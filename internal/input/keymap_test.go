func TestMacKeyCodeInvertsTangoTable(t *testing.T) {
	seen := make(map[uint16]uint16, len(tangoMacHIDKeys))
	for code, hid := range tangoMacHIDKeys {
		if prev, dup := seen[hid]; dup {
			t.Fatalf("Tango table maps HID 0x%02X from both 0x%02X and 0x%02X", hid, prev, code)
		}
		seen[hid] = code
		got, ok := MacKeyCode(hid)
		if !ok || got != code {
			t.Errorf("MacKeyCode(0x%02X) = 0x%02X, %v; want 0x%02X, true", hid, got, ok, code)
		}
	}
	if len(macKeyCodes) != len(tangoMacHIDKeys) {
		t.Errorf("reverse table has %d entries, Tango table has %d", len(macKeyCodes), len(tangoMacHIDKeys))
	}
	for hid, code := range macKeyCodes {
		if want, ok := tangoMacHIDKeys[code]; !ok || want != hid {
			t.Errorf("reverse entry HID 0x%02X -> 0x%02X has no matching Tango entry", hid, code)
		}
	}
}

