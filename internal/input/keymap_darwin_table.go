package input

// MacKeyCode maps a USB HID keyboard usage (page 0x07) to a macOS virtual key
// code (kVK_*), for injecting remote keystrokes with CGEventPost. ok is false
// for usages that have no macOS key code.
//
// The table is the exact inverse of the macOS keycode -> HID mapping used by
// Tango when it reports KeyEvent.HID, so a key pressed on a Mac viewer arrives
// on a Mac host as the same physical key.
func MacKeyCode(hid uint16) (code uint16, ok bool) {
	code, ok = macKeyCodes[hid]
	return code, ok
}

// macKeyCodes: HID usage -> macOS virtual key code.
var macKeyCodes = map[uint16]uint16{
	// Letters A-Z.
	0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03, // A B C D E F
	0x0A: 0x05, 0x0B: 0x04, 0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25, // G H I J K L
	0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23, 0x14: 0x0C, 0x15: 0x0F, // M N O P Q R
	0x16: 0x01, 0x17: 0x11, 0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07, // S T U V W X
	0x1C: 0x10, 0x1D: 0x06, // Y Z
	// Digits 1-9, 0.
	0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, 0x22: 0x17,
	0x23: 0x16, 0x24: 0x1A, 0x25: 0x1C, 0x26: 0x19, 0x27: 0x1D,
	// Editing and punctuation.
	0x28: 0x24, // Enter -> Return
	0x29: 0x35, // Escape
	0x2A: 0x33, // Backspace -> Delete
	0x2B: 0x30, // Tab
	0x2C: 0x31, // Space
	0x2D: 0x1B, // Minus
	0x2E: 0x18, // Equal
	0x2F: 0x21, // LeftBracket
	0x30: 0x1E, // RightBracket
	0x31: 0x2A, // Backslash
	0x33: 0x29, // Semicolon
	0x34: 0x27, // Quote
	0x35: 0x32, // Grave
	0x36: 0x2B, // Comma
	0x37: 0x2F, // Period
	0x38: 0x2C, // Slash
	0x39: 0x39, // CapsLock
	0x64: 0x0A, // Non-US Backslash -> ISO_Section
	// Function keys F1-F20.
	0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, 0x3E: 0x60, 0x3F: 0x61, // F1-F6
	0x40: 0x62, 0x41: 0x64, 0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F, // F7-F12
	0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A, 0x6C: 0x40, 0x6D: 0x4F, // F13-F18
	0x6E: 0x50, 0x6F: 0x5A, // F19 F20
	// Navigation.
	0x49: 0x72, // Insert -> Help
	0x4A: 0x73, // Home
	0x4B: 0x74, // PageUp
	0x4C: 0x75, // Delete Forward -> ForwardDelete
	0x4D: 0x77, // End
	0x4E: 0x79, // PageDown
	0x4F: 0x7C, // Right
	0x50: 0x7B, // Left
	0x51: 0x7D, // Down
	0x52: 0x7E, // Up
	0x65: 0x6E, // Application -> ContextMenu
	// Keypad.
	0x53: 0x47,                                                 // NumLock -> KeypadClear
	0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C, // / * - + Enter
	0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57, // 1-5
	0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B, 0x61: 0x5C, 0x62: 0x52, // 6-9 0
	0x63: 0x41, // Decimal
	0x67: 0x51, // Equals
	0x85: 0x5F, // Keypad Comma -> JIS_KeypadComma
	// Media keys that have key codes.
	0x7F: 0x4A, 0x80: 0x48, 0x81: 0x49, // Mute VolumeUp VolumeDown
	// JIS.
	0x87: 0x5E, // International1 (Ro) -> JIS_Underscore
	0x89: 0x5D, // International3 (Yen) -> JIS_Yen
	0x90: 0x68, // LANG1 -> JIS_Kana
	0x91: 0x66, // LANG2 -> JIS_Eisu
	// Modifiers.
	0xE0: 0x3B, 0xE1: 0x38, 0xE2: 0x3A, 0xE3: 0x37, // left Control Shift Option Command
	0xE4: 0x3E, 0xE5: 0x3C, 0xE6: 0x3D, 0xE7: 0x36, // right Control Shift Option Command
}
